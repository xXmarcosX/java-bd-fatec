    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (RaField.getText().isEmpty() || 
                NomeField.getText().isEmpty() ||
                EmailField.getText().isEmpty() ||
                CelularField.getText().isEmpty() ||
                SemestreField.getText().isEmpty()
                ) {
            JOptionPane.showMessageDialog(this, "Nenhum campo pode estar vazio");
        } else {
            Aluno aluno = new Aluno(
                    RaField.getText(),
                    NomeField.getText(),
                    EmailField.getText(),
                    CelularField.getText(),
                    Integer.parseInt(SemestreField.getText())
            );
            AlunoDAO dao = new AlunoDAO();
            
            dao.adicionarAluno(aluno);
            
            JOptionPane.showMessageDialog(this, "Aluno cadastro com sucesso!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

